# Generate each TS file.
# Note: we need to separate homeContent and converterText from the main structure in the generated TS.

def write_locale_file(code, data):
    filename = f"{locales_dir}/{code}.ts"
    
    # Extract homeContent
    home_content = {}
    converter_text = {}
    
    for key, val in data.items():
        if key.startswith("_"):
            converter_text[key[1:]] = val
        elif key == "formats" or key == "statuses":
            # For en and zh, they are mixed. Let's handle formats & statuses properly.
            pass
        else:
            home_content[key] = val
            
    # For sub-objects under converterText
    converter_text["formats"] = data.get("_formats", data.get("formats", {"png": "PNG", "jpg": "JPG", "webp": "WebP"}))
    converter_text["statuses"] = data.get("_statuses", data.get("statuses", {"idle": "idle", "processing": "processing", "ready": "ready", "error": "error"}))
    
    # Output TS
    content = f'''import {{ LocaleData }} from "../types";

export const {code}: LocaleData = {{
  homeContent: {json.dumps(home_content, ensure_ascii=False, indent=2)},
  converterText: {json.dumps(converter_text, ensure_ascii=False, indent=2)}
}};
'''
    with open(filename, "w", encoding="utf-8") as f:
        f.write(content)
    print(f"Created {filename}")

